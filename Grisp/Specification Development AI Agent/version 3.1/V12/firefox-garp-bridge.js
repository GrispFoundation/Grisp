'use strict';

/*
 * GSDA/3.1 Firefox -> GARP worker.
 *
 * This is a real browser automation process. It uses Selenium WebDriver to
 * drive Firefox, while GARP remains the deterministic GSDA boundary.
 *
 * Required environment variables:
 *   GSDA_PROMPT
 *   GSDA_PROVIDER_URL
 *   GSDA_PROMPT_SELECTOR
 *   GSDA_RESPONSE_SELECTOR
 *
 * Optional:
 *   GSDA_SEND_SELECTOR       click a send button instead of Enter
 *   GSDA_PEER_ID             default peer:alpha
 *   GSDA_FINGERPRINT         default local|adapter:firefox|endpoint:firefox
 *   GSDA_HMAC_SECRET         default development-secret
 *   GSDA_GARP_HOST           default 127.0.0.1
 *   GSDA_GARP_PORT           default 9911
 *   GSDA_SESSION_ID          autogenerated if omitted
 *   GSDA_TAB_ID              autogenerated if omitted
 *   GSDA_CONFIDENCE          default 900
 *   GSDA_RESPONSE_TIMEOUT_MS default 180000
 *   GSDA_STABLE_MS           default 2500
 *   GSDA_POLL_MS             default 500
 *   GSDA_HEADLESS            true/false, default false
 *   GSDA_PROFILE             path to an existing Firefox profile
 *   GECKODRIVER_PATH         path to geckodriver, when not on PATH
 *
 * Notes:
 *   - Login is deliberately not automated. Start Firefox with the required
 *     profile/session or log in interactively.
 *   - Selectors are provider-specific configuration, not kernel logic.
 */

const net = require('net');
const crypto = require('crypto');
const {Builder, By, Key, until} = require('selenium-webdriver');
const firefox = require('selenium-webdriver/firefox');

function env(name, fallback = undefined) {
    const value = process.env[name];
    return value === undefined || value === '' ? fallback : value;
}

function requiredEnv(name) {
    const value = env(name);
    if (!value) throw new Error(`Missing environment variable ${name}`);
    return value;
}

function canonicalObject(object) {
    const result = {};
    for (const key of Object.keys(object).sort()) result[key] = object[key];
    return JSON.stringify(result);
}

function sha256(value) {
    return crypto.createHash('sha256').update(Buffer.from(value, 'utf8')).digest('hex');
}

function hmac(secret, value) {
    return crypto.createHmac('sha256', Buffer.from(secret, 'utf8')).update(Buffer.from(value, 'utf8')).digest('hex');
}

function uuid() {
    return crypto.randomUUID();
}

class GarpClient {
    constructor(host, port, sessionId, tabId) {
        this.host = host;
        this.port = port;
        this.sessionId = sessionId;
        this.tabId = tabId;
        this.sequence = 0;
        this.socket = null;
        this.buffer = Buffer.alloc(0);
        this.pending = new Map();
    }

    connect() {
        return new Promise((resolve, reject) => {
            this.socket = net.createConnection({host: this.host, port: this.port}, resolve);
            this.socket.on('data', data => this.onData(data));
            this.socket.on('error', error => {
                for (const pending of this.pending.values()) pending.reject(error);
                this.pending.clear();
            });
            this.socket.on('close', () => {
                const error = new Error('GARP connection closed');
                for (const pending of this.pending.values()) pending.reject(error);
                this.pending.clear();
            });
        });
    }

    onData(data) {
        this.buffer = Buffer.concat([this.buffer, data]);
        while (this.buffer.length >= 4) {
            const length = this.buffer.readUInt32BE(0);
            if (this.buffer.length < 4 + length) return;
            const payload = this.buffer.subarray(4, 4 + length).toString('utf8');
            this.buffer = this.buffer.subarray(4 + length);
            let response;
            try {
                response = JSON.parse(payload);
            } catch (error) {
                continue;
            }
            const pending = this.pending.get(response.request_id);
            if (!pending) continue;
            this.pending.delete(response.request_id);
            pending.resolve(response);
        }
    }

    call(payload) {
        const requestId = uuid();
        const message = {
            schema: 'garp/1.0',
            message_type: 'command',
            request_id: requestId,
            session_id: this.sessionId,
            tab_id: this.tabId,
            sequence: ++this.sequence,
            payload
        };
        const encoded = Buffer.from(JSON.stringify(message), 'utf8');
        const frame = Buffer.allocUnsafe(4 + encoded.length);
        frame.writeUInt32BE(encoded.length, 0);
        encoded.copy(frame, 4);

        return new Promise((resolve, reject) => {
            this.pending.set(requestId, {resolve, reject});
            this.socket.write(frame);
        });
    }

    close() {
        if (this.socket) this.socket.end();
    }
}

async function waitForStableResponse(driver, selector, timeoutMs, stableMs, pollMs, baseline) {
    const deadline = Date.now() + timeoutMs;
    let lastText = '';
    let stableSince = 0;

    while (Date.now() < deadline) {
        const elements = await driver.findElements(By.css(selector));
        if (elements.length > 0) {
            const element = elements[elements.length - 1];
            const text = (await element.getText()).trim();
            if (text && text !== baseline) {
                if (text === lastText) {
                    if (!stableSince) stableSince = Date.now();
                    if (Date.now() - stableSince >= stableMs) return text;
                } else {
                    lastText = text;
                    stableSince = Date.now();
                }
            }
        }
        await new Promise(resolve => setTimeout(resolve, pollMs));
    }
    throw new Error('Timed out waiting for a stable assistant response');
}

async function main() {
    const prompt = requiredEnv('GSDA_PROMPT');
    const providerUrl = requiredEnv('GSDA_PROVIDER_URL');
    const promptSelector = requiredEnv('GSDA_PROMPT_SELECTOR');
    const responseSelector = requiredEnv('GSDA_RESPONSE_SELECTOR');
    const sendSelector = env('GSDA_SEND_SELECTOR');

    const peerId = env('GSDA_PEER_ID', 'peer:alpha');
    const fingerprint = env('GSDA_FINGERPRINT', 'local|adapter:firefox|endpoint:firefox');
    const secret = env('GSDA_HMAC_SECRET', 'development-secret');
    const garpHost = env('GSDA_GARP_HOST', '127.0.0.1');
    const garpPort = Number(env('GSDA_GARP_PORT', '9911'));
    const sessionId = env('GSDA_SESSION_ID', `session:${uuid()}`);
    const tabId = env('GSDA_TAB_ID', `tab:${uuid()}`);
    const confidence = Number(env('GSDA_CONFIDENCE', '900'));
    const timeoutMs = Number(env('GSDA_RESPONSE_TIMEOUT_MS', '180000'));
    const stableMs = Number(env('GSDA_STABLE_MS', '2500'));
    const pollMs = Number(env('GSDA_POLL_MS', '500'));
    const headless = env('GSDA_HEADLESS', 'false').toLowerCase() === 'true';
    const profile = env('GSDA_PROFILE');
    const geckodriverPath = env('GECKODRIVER_PATH');

    const garp = new GarpClient(garpHost, garpPort, sessionId, tabId);
    await garp.connect();

    let driver;
    try {
        const options = new firefox.Options();
        if (headless) options.addArguments('-headless');
        if (profile) options.setProfile(profile);

        const builder = new Builder().forBrowser('firefox').setFirefoxOptions(options);
        if (geckodriverPath) builder.setFirefoxService(new firefox.ServiceBuilder(geckodriverPath));
        driver = await builder.build();

        await driver.get(providerUrl);
        const promptElement = await driver.wait(
            until.elementLocated(By.css(promptSelector)),
            30000,
            'Prompt element not found'
        );

        const responseElementsBefore = await driver.findElements(By.css(responseSelector));
        let baseline = '';
        if (responseElementsBefore.length > 0) {
            baseline = (await responseElementsBefore[responseElementsBefore.length - 1].getText()).trim();
        }

        await promptElement.click();
        await promptElement.sendKeys(prompt);
        if (sendSelector) {
            const sendButton = await driver.findElement(By.css(sendSelector));
            await sendButton.click();
        } else {
            await promptElement.sendKeys(Key.ENTER);
        }

        const responseText = await waitForStableResponse(
            driver,
            responseSelector,
            timeoutMs,
            stableMs,
            pollMs,
            baseline
        );

        const contentCanonical = canonicalObject({
            content: responseText,
            schema: 'gsp/3.1'
        });
        const contentId = `content:${sha256(contentCanonical)}`;
        const payload = JSON.stringify({
            schema: 'gsp/3.1',
            content: responseText,
            content_id: contentId
        });

        const runResponse = await garp.call({
            command: 'create_task',
            user_prompt: prompt,
            user_intent: 'Generate a specification candidate from the Firefox AI peer response. [CRITICAL]',
            domain: 'specification-development'
        });
        if (runResponse.payload && runResponse.payload.accepted === 'False') {
            throw new Error(runResponse.payload.error_message || 'create_task rejected');
        }
        const taskId = runResponse.payload.task_id;

        const startResponse = await garp.call({command: 'start_run', task_id: taskId});
        const runId = startResponse.payload.run_id;
        const roundId = `round:${runId}:0`;
        const token = hmac(secret, `${peerId}|${fingerprint}|${roundId}`);

        const roundResponse = await garp.call({
            command: 'execute_round',
            run_id: runId,
            inputs: [{
                peer_id: peerId,
                fingerprint,
                token,
                kind: 0,
                confidence,
                payload
            }]
        });

        if (roundResponse.payload && roundResponse.payload.accepted === 'false') {
            throw new Error(roundResponse.payload.error_message || 'execute_round rejected');
        }

        const freezeResponse = await garp.call({
            command: 'freeze_candidate',
            run_id: runId
        });

        console.log(JSON.stringify({
            schema: 'firefox_garp_result/1.0',
            task_id: taskId,
            run_id: runId,
            candidate_artifact_id: roundResponse.payload.candidate_artifact_id,
            winning_peer_id: roundResponse.payload.winning_peer_id,
            spec_content_id: freezeResponse.payload.spec_content_id,
            content_id: contentId
        }, null, 2));
    } finally {
        if (driver) await driver.quit();
        garp.close();
    }
}

main().catch(error => {
    console.error(error.stack || error.message || error);
    process.exitCode = 1;
});
